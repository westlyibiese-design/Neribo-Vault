package com.westly.neribovault.feature.coder.buildflow

/**
 * Writes the GitHub Actions file that builds a project. The text is fixed apart from the Node version, the install
 * and build commands, the output folder and the names of the variables, all of which are checked values or values
 * from the plan's fixed sets, so nothing here needs YAML escaping. Variable values are never in the file: GitHub
 * reads them from the repository's own variables when the build runs.
 */
object CoderBuildWorkflow {
    /** Where the file lives in the project, and so in the repository. */
    const val WORKFLOW_PATH = ".github/workflows/coder-build.yml"

    /** The file name GitHub is asked to run. */
    const val WORKFLOW_FILE = "coder-build.yml"

    /** The first line of every file Coder writes. A file with another first line is never touched. */
    const val MARKER = "# Generated by Neribo Vault Coder. You can edit this file."

    /** The name of the artifact the build uploads and Coder downloads. */
    const val ARTIFACT_NAME = "coder-dist"

    /** What the wizard says when the workflow path is taken by a file Coder did not write. */
    const val MSG_FOREIGN_FILE =
        "A file named coder-build.yml already exists and was not made by Coder. Rename or delete it, then try again."

    /** True when [existingText] starts with the marker line, so Coder wrote it and may replace it. */
    fun isOurs(existingText: String): Boolean = existingText.lineSequence().firstOrNull()?.trimEnd() == MARKER

    /**
     * The workflow text for [plan] and the variable names [variableNames] (names only; each appears once, in
     * alphabetical order). An output folder that is not a plain folder name is replaced by `dist`, so the text can
     * never carry anything but a folder name there.
     */
    fun generate(plan: CoderBuildPlan, variableNames: List<String>): String {
        val outputDir = if (CoderPackageAnalyzer.isValidOutputDir(plan.outputDir)) plan.outputDir else "dist"
        val out = StringBuilder()
        out.append(MARKER).append('\n')
        out.append("name: Coder build\n")
        out.append("on:\n")
        out.append("  workflow_dispatch:\n")
        out.append("permissions:\n")
        out.append("  contents: read\n")
        out.append("jobs:\n")
        out.append("  build:\n")
        out.append("    runs-on: ubuntu-latest\n")
        out.append("    timeout-minutes: 15\n")
        out.append("    env:\n")
        out.append("      CI: \"false\"\n")
        for (name in variableNames.distinct().sorted()) {
            out.append("      ").append(name).append(": \${{ vars.").append(name).append(" }}\n")
        }
        out.append("    steps:\n")
        out.append("      - uses: actions/checkout@v4\n")
        out.append("      - uses: actions/setup-node@v4\n")
        out.append("        with:\n")
        out.append("          node-version: ").append(plan.nodeVersion).append('\n')
        out.append("      - name: Install\n")
        out.append("        run: ").append(plan.installCommand).append('\n')
        out.append("      - name: Build\n")
        out.append("        run: ").append(plan.buildCommand).append('\n')
        out.append("      - uses: actions/upload-artifact@v4\n")
        out.append("        with:\n")
        out.append("          name: ").append(ARTIFACT_NAME).append('\n')
        out.append("          path: ").append(outputDir).append('\n')
        out.append("          if-no-files-found: error\n")
        out.append("          retention-days: 7\n")
        return out.toString()
    }
}
